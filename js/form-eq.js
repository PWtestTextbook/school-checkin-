function eqResultHtml(r) {
  const cls = (l) => (l === "อยู่ในเกณฑ์ปกติ" ? "ok" : l === "สูงกว่าเกณฑ์ปกติ" ? "ok" : "late");
  const row = (n, s, rg, l, sum) => `<tr class="${sum ? "sum" : ""}"><td>${App.esc(n)}</td><td class="num">${s}</td><td class="num muted">${rg}</td><td><span class="badge ${cls(l)}">${App.esc(l)}</span></td></tr>`;
  let html = "";
  for (const g of r.groups) {
    html += r.subs.filter((s) => s.group === g.name).map((s) => row("· " + s.name, s.score, s.range, s.level)).join("");
    html += row("ด้าน" + g.name, g.score, g.range, g.level, true);
  }
  html += row("EQ รวม", r.total, r.totalRange, r.totalLevel, true);
  return `<table class="result"><thead><tr><th>ด้าน</th><th>คะแนน</th><th>ช่วงปกติ</th><th>แปลผล</th></tr></thead><tbody>${html}</tbody></table>`;
}
