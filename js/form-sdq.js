/**
 * ขั้นตอนแบบประเมิน SDQ
 * version: "student" (นักเรียนประเมินตนเอง) | "teacher" (ครูประเมิน) | "parent" (ผู้ปกครองประเมิน โดยครูบันทึก)
 */
function sdqSteps(version = "student", studentName = "") {
  const student = version === "student";
  const items = student ? SDQ_ITEMS : SDQ_ITEMS_ADULT;
  const page = (from, to) => ({
    title: `ข้อ ${from}-${to}`,
    desc: (student ? "" : `ประเมิน: ${studentName} · `) + "ตอบให้ตรงความเป็นจริงที่เกิดขึ้นในช่วง 6 เดือนที่ผ่านมา",
    fields: items.slice(from - 1, to).map((t, i) => ({
      key: "q" + (from + i), num: from + i, label: t, type: "likert", required: true, options: SDQ_SCALE,
    })),
  });
  const hasProblem = (d) => Number(d.overall) > 0;
  const who = student ? "นักเรียน" : "เด็ก";
  const intro = student
    ? `<p>แบบประเมินนี้มี <b>25 ข้อ</b> และคำถามเพิ่มเติมอีกเล็กน้อย ใช้เวลาประมาณ 5-10 นาที</p>
       <p>อ่านแต่ละข้อแล้วเลือกคำตอบที่ตรงกับตัวเองมากที่สุด <b>ในช่วง 6 เดือนที่ผ่านมา</b> ไม่มีคำตอบถูกหรือผิด ขอให้ตอบตามความเป็นจริง</p>`
    : `<p>${version === "teacher" ? "ครูประเมินพฤติกรรมของ" : "ผู้ปกครองประเมินพฤติกรรมของ"} <b>${App.esc(studentName)}</b> 25 ข้อ ตามที่สังเกตได้<b>ในช่วง 6 เดือนที่ผ่านมา</b></p>
       ${version === "parent" ? "<p>ครูอ่านข้อคำถามให้ผู้ปกครองฟัง แล้วบันทึกคำตอบของผู้ปกครอง</p>" : ""}`;
  const impactAreas = version === "teacher"
    ? [["friends", "ง1", "การคบเพื่อน"], ["classroom", "ง2", "การเรียนในห้องเรียน"]]
    : [["home", "ง1", "ความเป็นอยู่ที่บ้าน"], ["friends", "ง2", "การคบเพื่อน"], ["classroom", "ง3", "การเรียนในห้องเรียน"], ["leisure", "ง4", "กิจกรรมยามว่าง"]];
  const burdenLabel = { student: "ปัญหานี้ทำให้คนรอบข้างเกิดความยุ่งยากหรือไม่ (ครอบครัว เพื่อน ครู เป็นต้น)",
    teacher: "ปัญหาของเด็กทำให้คุณหรือชั้นเรียนเกิดความยุ่งยากหรือไม่", parent: "ปัญหานี้ทำให้คุณหรือครอบครัวเกิดความยุ่งยากหรือไม่" }[version];

  const first = { title: "คำชี้แจง", fields: [{ type: "info", html: `<div class="intro">${intro}
      <div class="scale-demo"><span>ไม่จริง</span><span>ค่อนข้างจริง</span><span>จริง</span></div>
      <p class="privacy">ข้อมูลนี้เป็นความลับ ใช้เพื่อการดูแลช่วยเหลือนักเรียนเท่านั้น</p></div>` }] };
  if (version === "parent") {
    first.fields.push({ key: "respondent", label: "ผู้ตอบแบบประเมิน", type: "radio", required: true, other: true, options: ["พ่อ", "แม่"] });
  }
  return [
    first,
    page(1, 5), page(6, 10), page(11, 15), page(16, 20), page(21, 25),
    {
      title: "คำถามเพิ่มเติม",
      fields: [
        { key: "overall", type: "likert", num: "ก", required: true, options: ["ไม่", "ใช่ มีปัญหาเล็กน้อย", "ใช่ มีปัญหาชัดเจน", "ใช่ มีปัญหาอย่างมาก"],
          label: student
            ? "โดยรวม นักเรียนคิดว่าตัวเองมีปัญหาในด้านใดด้านหนึ่งต่อไปนี้หรือไม่: ด้านอารมณ์ ด้านสมาธิ ด้านพฤติกรรม หรือความสามารถเข้ากับผู้อื่น"
            : "โดยรวมแล้วคุณคิดว่าเด็กมีปัญหาในด้านใดด้านหนึ่งต่อไปนี้หรือไม่: ด้านอารมณ์ ด้านสมาธิ ด้านพฤติกรรม หรือความสามารถเข้ากับผู้อื่น" },
        { key: "duration", type: "likert", num: "ข", required: true, show: hasProblem,
          options: ["น้อยกว่า 1 เดือน", "1-5 เดือน", "6-12 เดือน", "มากกว่า 1 ปี"], label: "ปัญหานี้เกิดขึ้นมานานเท่าไรแล้ว" },
        { key: "distress", type: "likert", num: "ค", required: true, show: hasProblem, options: DEGREE,
          label: `ปัญหานี้ทำให้${who}รู้สึกไม่สบายใจหรือไม่` },
        { type: "info", html: `<h3 class='sub'>ปัญหานี้รบกวนชีวิตประจำวันของ${who}ในด้านต่อไปนี้หรือไม่</h3>`, show: hasProblem },
        ...impactAreas.map(([key, num, label]) => ({ key, num, label, type: "likert", required: true, show: hasProblem, options: DEGREE })),
        { key: "burden", type: "likert", num: "จ", required: true, show: hasProblem, options: DEGREE, label: burdenLabel },
        { key: "comment", label: student ? "นักเรียนมีอย่างอื่นที่จะบอกอีกหรือไม่" : "คุณมีความเห็นหรือความกังวลอื่นอีกหรือไม่",
          type: "textarea", maxlength: 500 },
      ],
    },
  ];
}

/** ตารางผลคะแนน SDQ (แสดงเมื่อเปิดให้นักเรียนเห็นผล) */
function sdqResultHtml(r) {
  const cls = (l) => (l.startsWith("ปกติ") ? "ok" : l === "เสี่ยง" ? "late" : "absent");
  const row = (name, score, lv, sum) => `<tr class="${sum ? "sum" : ""}"><td>${App.esc(name)}</td><td class="num">${score}</td><td><span class="badge ${cls(lv)}">${App.esc(lv)}</span></td></tr>`;
  return `<table class="result"><thead><tr><th>ด้าน</th><th>คะแนน</th><th>แปลผล</th></tr></thead><tbody>
    ${Object.values(r.scales).map((s) => row(s.name, s.score, s.level)).join("")}
    ${row("รวม 4 ด้าน", r.total, r.totalLevel, true)}
    ${row(r.prosocial.name, r.prosocial.score, r.prosocial.level)}
    ${row("ผลกระทบ (ด้านหลัง)", r.impact, r.impactLevel)}
  </tbody></table>`;
}
